from contextlib import closing, contextmanager
from pathlib import Path
import sqlite3


SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (owner TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS calculations (
    sequence {sequence_type} PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    owner TEXT NOT NULL REFERENCES sessions(owner),
    created_at TEXT NOT NULL,
    calculator TEXT NOT NULL,
    title TEXT NOT NULL,
    inputs TEXT NOT NULL,
    summary TEXT NOT NULL,
    details TEXT NOT NULL,
    unit TEXT NOT NULL,
    numerical_result TEXT
);
CREATE INDEX IF NOT EXISTS calculations_owner_sequence ON calculations(owner, sequence);
"""


class Session:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, sql, params=()):
        # Only application SQL is translated. All user values remain bound parameters.
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.connection.execute(sql, params)

    @contextmanager
    def write(self, owner=None):
        transaction = self.connection.transaction() if self.postgres else self.connection
        with transaction:
            # PostgreSQL can have simultaneous writers. Serialize one user's mutations
            # so concurrent inserts still retain exactly the most recent 50 entries.
            if self.postgres and owner:
                self.execute("SELECT owner FROM sessions WHERE owner=? FOR UPDATE", (owner,))
            yield


class Database:
    def __init__(self, path, url=None):
        self.postgres = bool(url)
        if url:
            if not url.startswith(("postgresql://", "postgres://")):
                raise ValueError("DATABASE_URL должен указывать на PostgreSQL.")
            import psycopg
            from psycopg.rows import dict_row
            self.error = psycopg.Error
            self.connect = lambda: psycopg.connect(url, autocommit=True, connect_timeout=10, row_factory=dict_row)
            try:
                with closing(self.connect()) as conn, conn.transaction():
                    conn.execute("SELECT pg_advisory_xact_lock(638464578)")
                    conn.execute(SCHEMA.format(sequence_type="BIGINT GENERATED BY DEFAULT AS IDENTITY"))
            except psycopg.Error:
                raise RuntimeError("Не удалось подключиться к PostgreSQL или подготовить таблицы.") from None
        else:
            path = Path(path)
            path.parent.mkdir(parents=True, exist_ok=True)
            self.error = sqlite3.Error
            self.connect = lambda: sqlite3.connect(path, timeout=10)
            with closing(self.connect()) as conn:
                conn.execute("PRAGMA journal_mode=WAL")
                conn.executescript(SCHEMA.format(sequence_type="INTEGER"))

    @contextmanager
    def session(self):
        with closing(self.connect()) as conn:
            if not self.postgres:
                conn.row_factory = sqlite3.Row
                conn.execute("PRAGMA foreign_keys=ON")
            yield Session(conn, self.postgres)
